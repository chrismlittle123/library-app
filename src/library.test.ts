import { NoteSearch, fold } from "./search";
import type { NoteRecord } from "./sync/store";
import {
  diaryPath,
  displayName,
  fillTemplate,
  isConflictCopy,
  isGenerated,
  listFolder,
  newNotePath,
  noteName,
  noteTitle,
  prettify,
} from "./library";

function note(path: string, text = "", dirty = false): NoteRecord {
  return { path, text, baseSha: null, dirty, rev: 1, updatedAt: 0 };
}

describe("library paths", () => {
  const date = new Date(2026, 0, 5);

  it("builds the diary path", () => {
    expect(diaryPath(date)).toBe("diary/daily/2026/01/2026-01-05.md");
  });

  it("fills the Obsidian date placeholder", () => {
    expect(fillTemplate("# {{date:YYYY-MM-DD}}\n", date)).toBe("# 2026-01-05\n");
  });

  it("makes a safe new note path", () => {
    expect(newNotePath("inbox", "  a/b: idea.md ")).toBe("inbox/a b idea.md");
    expect(newNotePath("", "top")).toBe("top.md");
    expect(newNotePath("inbox", " ../ ")).toBeNull();
  });

  it("recognises titles, generated views and conflict copies", () => {
    expect(noteTitle("a/b/c.md")).toBe("c");
    expect(isGenerated("<!-- generated by pipeline/render_views.py — do not edit -->\n")).toBe(true);
    expect(isGenerated("# do this\n" + " ".repeat(200) + "do not edit")).toBe(false);
    expect(isConflictCopy("a (phone conflict 2026-11-03 1405).md")).toBe(true);
  });
});

describe("listFolder", () => {
  const notes = [
    note("top.md"),
    note("recipes/b.md"),
    note("recipes/a.md", "", true),
    note("recipes/sub/c.md"),
    note("diary/daily/2025/x.md"),
    note("diary/daily/2026/y.md"),
  ];

  it("lists folders with counts at the top", () => {
    const view = listFolder(notes, "");
    expect(view.notes.map((n) => n.path)).toEqual(["top.md"]);
    expect(view.folders.map((f) => [f.name, f.count, f.unsynced])).toEqual([
      ["diary", 2, 0],
      ["recipes", 3, 1],
    ]);
  });

  it("sorts A to Z generally", () => {
    expect(listFolder(notes, "recipes").notes.map((n) => n.path)).toEqual([
      "recipes/a.md",
      "recipes/b.md",
    ]);
  });

  it("sorts the diary newest first", () => {
    expect(listFolder(notes, "diary/daily").folders.map((f) => f.name)).toEqual(["2026", "2025"]);
  });
});

describe("NoteSearch", () => {
  function search(...notes: NoteRecord[]) {
    const index = new NoteSearch();
    index.sync(notes);
    return index;
  }

  it("finds words in the body and shows them in the snippet", () => {
    const [hit] = search(note("a.md", "x ".repeat(100) + "a heron by the bridge")).search("heron");
    expect(hit.path).toBe("a.md");
    expect(hit.snippet).toContain("heron");
    expect(hit.snippet.startsWith("…")).toBe(true);
  });

  it("ranks title matches first", () => {
    const hits = search(note("other.md", "soup soup"), note("soup.md", "nothing")).search("soup");
    expect(hits[0].path).toBe("soup.md");
  });

  it("ignores accents and case", () => {
    expect(fold("Señorío")).toBe("senorio");
    expect(search(note("a.md", "Señorío del Bierzo")).search("senorio")).toHaveLength(1);
    expect(search(note("a.md", "senorio")).search("SEÑORÍO")).toHaveLength(1);
  });

  it("copes with a typo and a partial word", () => {
    const index = search(note("a.md", "tomatoes and garlic"));
    expect(index.search("tomatos")).toHaveLength(1);
    expect(index.search("garl")).toHaveLength(1);
  });

  it("needs every word to match", () => {
    expect(search(note("a.md", "river heron"), note("b.md", "river")).search("river heron")).toHaveLength(1);
  });

  it("returns nothing for an empty query", () => {
    expect(search(note("a.md", "x")).search("  ")).toEqual([]);
  });

  it("follows edits and deletions", () => {
    const index = search(note("a.md", "old words"), note("b.md", "keep"));
    index.sync([note("a.md", "new words"), note("b.md", "keep")]);
    expect(index.search("old")).toEqual([]);
    expect(index.search("new")).toHaveLength(1);
    index.sync([note("b.md", "keep")]);
    expect(index.search("new")).toEqual([]);
    expect(index.search("keep")).toHaveLength(1);
  });
});

describe("display names", () => {
  it("reads a filename as words", () => {
    expect(prettify("roast-potatoes")).toBe("Roast potatoes");
    expect(prettify("economic_history")).toBe("Economic history");
    expect(prettify("iPhone-notes")).toBe("iPhone notes");
    expect(prettify("tv")).toBe("TV");
  });

  it("reads diary dates and month folders as dates", () => {
    expect(displayName("diary/daily/2026/11/2026-11-10.md")).toBe("Tuesday 10 November 2026");
    expect(displayName("diary/daily/2026/11")).toBe("November");
    expect(displayName("diary/daily/2026")).toBe("2026");
  });

  it("keeps the date in a conflict copy's name", () => {
    expect(displayName("recipes/roast-potatoes (phone conflict 2026-11-10 0930).md")).toBe(
      "Roast potatoes (phone conflict 2026-11-10 0930)",
    );
  });
});

describe("note names", () => {
  it("prefers the note's own heading, which keeps accents", () => {
    expect(noteName("recipes/alubias-espanolas.md", "# Alubias españolas\n\nBeans.")).toBe("Alubias españolas");
    expect(noteName("books/x.md", "---\ntags: [a]\n---\n# The Remains of the Day\n")).toBe("The Remains of the Day");
  });

  it("falls back to the filename without a usable heading", () => {
    expect(noteName("inbox/gift-ideas.md", "Some text\n# Later heading")).toBe("Gift ideas");
    expect(noteName("diary/daily/2026/11/2026-11-10.md", "# 2026-11-10\n")).toBe("Tuesday 10 November 2026");
    expect(noteName("templates/daily.md", "# {{date:YYYY-MM-DD}}\n")).toBe("Daily");
    expect(noteName("inbox/new.md", undefined)).toBe("New");
  });
});
